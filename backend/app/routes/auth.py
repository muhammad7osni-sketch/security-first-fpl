@limiter.limit("10/minute")  # Rate limit: 10 calls per minute
async def logout(request: Request, auth: AuthContext = Depends(require_auth)) -> dict:
    """
    Logout: Invalidate tokens and clear session.
    Requires valid Bearer token.
    
    Response:
        - status: "success"
    
    Never logs tokens.
    """
    try:
        user_id = auth.user_id
        # In Supabase, delete/invalidate tokens stored for this user
        # (handled in database setup step)

        logger.info("logout", extra={"user_id": user_id})

        return {"status": "success"}

    except Exception as e:
        logger.error("logout_error", extra={"error": str(e)})
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="Logout failed",
        )
